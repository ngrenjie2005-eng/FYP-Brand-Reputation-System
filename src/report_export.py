def docx_add_title(
    document,
    text,
):

    paragraph = (
        document.add_paragraph()
    )

    paragraph.alignment = (
        WD_ALIGN_PARAGRAPH.CENTER
    )

    run = paragraph.add_run(
        text
    )

    run.bold = True

    run.font.size = Pt(
        23
    )


def docx_add_centered_text(
    document,
    text,
    size=11,
    bold=False,
):

    paragraph = (
        document.add_paragraph()
    )

    paragraph.alignment = (
        WD_ALIGN_PARAGRAPH.CENTER
    )

    run = paragraph.add_run(
        str(text)
    )

    run.bold = bold

    run.font.size = Pt(
        size
    )


def docx_add_llm_report(
    document,
    report_text,
):
    """
    Convert the simple Markdown structure
    generated by the LLMs into Word elements.
    """

    if not report_text:
        return


    lines = (
        str(report_text)
        .splitlines()
    )


    for raw_line in lines:

        line = (
            raw_line.strip()
        )


        if not line:
            continue


        # --------------------------------------------
        # H1
        # --------------------------------------------

        if line.startswith(
            "# "
        ):

            document.add_heading(
                clean_markdown_text(
                    line[2:]
                ),
                level=1
            )


        # --------------------------------------------
        # H2
        # --------------------------------------------

        elif line.startswith(
            "## "
        ):

            document.add_heading(
                clean_markdown_text(
                    line[3:]
                ),
                level=2
            )


        # --------------------------------------------
        # H3
        # --------------------------------------------

        elif line.startswith(
            "### "
        ):

            document.add_heading(
                clean_markdown_text(
                    line[4:]
                ),
                level=3
            )


        # --------------------------------------------
        # BULLET
        # --------------------------------------------

        elif (
            line.startswith("- ")
            or
            line.startswith("• ")
        ):

            document.add_paragraph(
                clean_markdown_text(
                    line[2:]
                ),
                style="List Bullet"
            )


        # --------------------------------------------
        # NUMBERED ITEM
        # --------------------------------------------

        elif re.match(
            r"^\d+\.\s",
            line
        ):

            cleaned = re.sub(
                r"^\d+\.\s*",
                "",
                line
            )

            document.add_paragraph(
                clean_markdown_text(
                    cleaned
                ),
                style="List Number"
            )


        # --------------------------------------------
        # NORMAL PARAGRAPH
        # --------------------------------------------

        else:

            document.add_paragraph(
                clean_markdown_text(
                    line
                )
            )


