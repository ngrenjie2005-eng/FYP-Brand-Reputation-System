def pdf_add_llm_report(
    pdf,
    report_text,
):

    if not report_text:
        return


    lines = (
        str(report_text)
        .splitlines()
    )


    for raw_line in lines:

        line = (
            raw_line.strip()
        )


        if not line:
            continue


        if line.startswith(
            "# "
        ):

            pdf_add_heading(
                pdf,
                line[2:],
                level=1,
            )


        elif line.startswith(
            "## "
        ):

            pdf_add_heading(
                pdf,
                line[3:],
                level=2,
            )


        elif line.startswith(
            "### "
        ):

            pdf_add_heading(
                pdf,
                line[4:],
                level=3,
            )


        elif (
            line.startswith("- ")
            or
            line.startswith("• ")
        ):

            pdf_add_bullet(
                pdf,
                line[2:],
            )


        elif re.match(
            r"^\d+\.\s",
            line
        ):

            pdf_add_paragraph(
                pdf,
                line,
            )


        else:

            pdf_add_paragraph(
                pdf,
                line,
            )


def pdf_add_table(
    pdf,
    rows,
    column_widths,
):
    """
    Simple 2-column PDF table.
    """

    if not rows:
        return


    for (
        row_number,
        row
    ) in enumerate(
        rows
    ):

        if row_number == 0:

            pdf.set_fill_color(
                40,
                110,
                90,
            )


            pdf.set_text_color(
                255,
                255,
                255,
            )


            pdf.set_font(
                "Helvetica",
                "B",
                9,
            )


        else:

            pdf.set_fill_color(
                245,
                247,
                249,
            )


            pdf.set_text_color(
                45,
                45,
                45,
            )


            pdf.set_font(
                "Helvetica",
                "",
                9,
            )


        pdf.cell(
            column_widths[0],
            7,
            pdf_safe_text(
                row[0]
            ),
            border=1,
            fill=True,
        )


        pdf.cell(
            column_widths[1],
            7,
            pdf_safe_text(
                row[1]
            ),
            border=1,
            fill=True,
        )


