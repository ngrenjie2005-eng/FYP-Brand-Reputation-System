    # 3. CUSTOMER VOICE
    # ========================================================

    pdf_add_heading(
        pdf,
        (
            "3. Customer Voice "
            "Intelligence"
        ),
        level=1,
    )


    pdf_add_heading(
        pdf,
        (
            "3.1 Frequent "
            "Positive Terms"
        ),
        level=2,
    )


