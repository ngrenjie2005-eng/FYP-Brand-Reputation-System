def current_timestamp():
    """
    Return a readable report-generation timestamp.
    """

    return datetime.now().strftime(
        "%d %B %Y, %H:%M"
    )


def clean_markdown_text(
    text,
):
    """
    Remove simple Markdown formatting from text.
    """

    if text is None:
        return ""

    text = str(text)

    text = text.replace(
        "**",
        ""
    )

    text = text.replace(
        "__",
        ""
    )

    text = text.replace(
        "`",
        ""
    )

    return text.strip()


