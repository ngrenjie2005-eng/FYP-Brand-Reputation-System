class BrandPulsePDF(
    FPDF
):

    def header(
        self
    ):
        """
        Header shown from page 2 onward.
        """

        if self.page_no() > 1:

            self.set_font(
                "Helvetica",
                "B",
                9,
            )


            self.set_text_color(
                30,
                140,
                90,
            )


            self.cell(
                0,
                7,
                "BrandPulse AI - Brand Reputation Intelligence Report",
                align="C",
            )


            self.ln(
                9
            )


            self.set_draw_color(
                210,
                215,
                220,
            )


            self.line(
                15,
                self.get_y(),
                195,
                self.get_y(),
            )


            self.ln(
                4
            )


    def footer(
        self
    ):

        self.set_y(
            -14
        )


        self.set_font(
            "Helvetica",
            "",
            8,
        )


        self.set_text_color(
            110,
            110,
            110,
        )


        self.cell(
            0,
            8,
            (
                f"Page {self.page_no()}"
            ),
            align="C",
        )


